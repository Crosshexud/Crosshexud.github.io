EYES = {'bogomol-1': [(352, 813, 4)], 'bogomol-2': [(477, 997, 4)]}  # тёмный глаз — не зелёный, добавляем кругом

def dilate(m, n=1):
    for _ in range(n):
        p = np.pad(m, 1)
        m = p[1:-1, 1:-1] | p[:-2, 1:-1] | p[2:, 1:-1] | p[1:-1, :-2] | p[1:-1, 2:] | p[:-2, :-2] | p[:-2, 2:] | p[2:, :-2] | p[2:, 2:]
    return m

def erode(m, n=1):
    return ~dilate(~m, n)

def dilate4(m):
    p = np.pad(m, 1)
    return p[1:-1, 1:-1] | p[:-2, 1:-1] | p[2:, 1:-1] | p[1:-1, :-2] | p[1:-1, 2:]

def fill_holes(m):
    # всё, до чего нельзя дойти от края кадра, не наступая на маску, — дырка внутри богомола
    # (шагаем только по сторонам, не по диагонали — иначе «просачивается» сквозь тонкий край)
    out = np.zeros_like(m); out[0, :] = out[-1, :] = out[:, 0] = out[:, -1] = True
    out &= ~m
    while True:
        nxt = out | (dilate4(out) & ~m)
        if (nxt == out).all(): return ~out
        out = nxt

for name, (x1, y1, x2, y2) in BOX.items():
    im = np.asarray(Image.open(SRC + name + '.jpg').convert('RGB')).astype(int)
    H, W = im.shape[:2]
    cx1, cy1, cx2, cy2 = max(0, x1 - PAD), max(0, y1 - PAD), min(W, x2 + PAD), min(H, y2 + PAD)
    c = im[cy1:cy2, cx1:cx2]
    r, g, b = c[..., 0], c[..., 1], c[..., 2]
    # уверенно богомол: насыщенно-зелёное
    seed = (g > r + 10) & (g > b + 28) & (g > 95)
    # может быть богомолом — по оттенку: лапки и брюшко жёлто-зелёные и бежевые (оттенок от 30°),
    # а кожа (17–25°) и красные листья (4–16°) краснее; серые размытые пятна отсекает насыщенность
    mx, mn = c.max(-1), c.min(-1)
    sat = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1), 0)
    hue = np.zeros(mx.shape)
    d = np.maximum(mx - mn, 1)
    hue = np.where(mx == r, 60 * ((g - b) / d % 6), hue)
    hue = np.where(mx == g, 60 * ((b - r) / d + 2), hue)
    hue = np.where(mx == b, 60 * ((r - g) / d + 4), hue)
    cand = (hue >= 30) & (hue <= 170) & (sat >= 0.15) & (mx >= 110)  # тёмные ветки и тени — не богомол
    # растим маску от уверенных точек по похожим соседям; шаг в 2 точки перешагивает разрывы на суставах лапок
    m = seed.copy()
    for _ in range(400):
        nxt = m | (dilate(m, 2) & cand)
        if (nxt == m).all(): break
        m = nxt
    # закрываем полоски и дырочки на брюшке (небольшим радиусом — чтобы не заливать углы между лапкой и телом);
    # «крошки» не убираем: это стёрло бы тонкие лапки
    m = fill_holes(erode(dilate(m, 2), 2))
    full = np.zeros((H, W), np.uint8); full[cy1:cy2, cx1:cx2] = m * 255
    img = Image.fromarray(full)
    d = ImageDraw.Draw(img)
    for pts, w in LINES[name]:
        d.line(pts, fill=255, width=w, joint='curve')
        for x, y in (pts[0], pts[-1]): d.ellipse((x - w / 2, y - w / 2, x + w / 2, y + w / 2), fill=255)  # круглые концы
    for x, y, rr in EYES[name]: d.ellipse((x - rr, y - rr, x + rr, y + rr), fill=255)
    out = img.filter(ImageFilter.GaussianBlur(0.8))
    out.save(SRC + name + '-mask.png')
    print(name, 'точек богомола:', int(m.sum()), 'было (только ярко-зелёные):', int(seed.sum()))
